"""get_limits — Список продуктовых лимитов по договору, карте и группе карт

Что делает
    Получает продуктовые лимиты договора, карты или группы. Передаёт contract_id и
    опциональный card_id/group_id, выводит список лимитов.
    Изменяет данные: нет. Тарификация: нет. Демо-стенд: да.
    Вызов SDK: client.limits.get_limits(...)
    Раздел спецификации 1.1.60: Список продуктовых лимитов по договору, карте и группе карт

HTTP-запрос
      GET /v1/limit
    Параметры передаются: строка запроса.
    contract_id передаётся: header, query.
    Заголовки: api_key, date_time, session_id (после авторизации).

Параметры метода SDK
      contract_id: str | None, необязательный, по умолчанию None, тип в спецификации: string — ID договора
      card_id: str | None, необязательный, по умолчанию None, тип в спецификации: string — ID карты. Если ID карты и ID группы карт не переданы, то будут возвращены все продуктовые лимиты, привязанные к договору. Если передан ID карты, то будет возвращена информация о всех продуктовых лимитах по карте, даже если передан ID группы карт
      group_id: str | None, необязательный, по умолчанию None, тип в спецификации: string — ID группы карт. Если передан ID группы карты, то будут возвращены все продуктовые лимиты указанной группы карт. Если передан ID карты и ID группы карт, то будет возвращена информация по карте

Модели проверки входящих данных (запрос)
      отдельной модели нет: параметры проверяются сигнатурой и проверками метода

Модели проверки исходящих данных (ответ API)
    LimitsResponse:
      status: ResponseStatus, обязательное — Статус ответа API
      data: LimitsData, обязательное — Типизированные данные ответа API
      timestamp: int | None, необязательное — Метка времени ответа API
    ResponseStatus:
      code: int, обязательное — Код выполнения API-операции
      message: str | None, необязательное — Текст статуса API-операции
      errors: list[dict[str, object]] | None, необязательное — Массив ошибок; отсутствует, если операция завершилась без ошибок
    LimitsData:
      total_count: int, обязательное — Общее количество лимитов
      result: list[LimitItem] | None, необязательное — Список лимитов
    LimitItem:
      id: str, обязательное — ID лимита
      card_id: str | None, необязательное — ID карты, если лимит задан для карты
      group_id: str | None, необязательное — ID группы карт, если лимит задан для группы
      contract_id: str, обязательное — ID договора, к которому относится лимит
      productGroup: str | None, необязательное — ID группы продуктов
      productType: str, обязательное — ID типа продукта
      amount: LimitAmount | None, необязательное — Ограничение по объёму (литры и т.д.)
      sum: LimitSum | None, необязательное — Ограничение по сумме в валюте договора
      term: LimitTerm | None, необязательное — Периодичность и временные ограничения
      transactions: LimitTransactions | None, необязательное — Ограничения по количеству транзакций
      time: LimitTime, обязательное — Периодичность сброса лимита
      date: str, обязательное — Дата создания лимита (формат dd/mm/yyyy hh:mm:ss)
    LimitAmount:
      value: float, обязательное — Установленное значение лимита
      used: float, обязательное — Использованное значение лимита
      unit: str, обязательное — Единица измерения (например, 'LIT' или 'RUB')
    LimitSum:
      currency: str, обязательное — Код валюты (например, 810)
      value: float, обязательное — Сумма лимита
      used: float, обязательное — Использованный объём лимита
    LimitTerm:
      days: str | None, необязательное — Дни недели (например, '1111100' для Пн–Пт)
      type: int, обязательное — Тип периода (1 — будни, 2 — ежедневно и т.д.)
      time: LimitTermTime | None, необязательное — Временной диапазон действия
    LimitTermTime:
      from: str, обязательное — Время начала действия лимита (HH:MM)
      to: str, обязательное — Время окончания действия лимита (HH:MM)
    LimitTransactions:
      count: int, обязательное — Максимальное количество транзакций
      occured: int, обязательное — Фактическое количество транзакций
    LimitTime:
      number: int, обязательное — Период в числовом виде (например, 3)
      type: int, обязательное — Тип периода (например, 7 — неделя)

Возможные ошибки
    До отправки запроса (локальные проверки SDK):
      validate_card_or_group_target() — RequestValidationError при недопустимом значении
      pydantic.ValidationError / RequestValidationError — неверный тип или формат
      параметра по модели запроса.
    Ответ API (HTTP-код или status.code; текст сервера — в «Сообщение сервера: …»):
      400 ValidationError — неверные параметры или структура запроса;
      401 NotAuthenticatedError — сессия недействительна (SDK один раз авторизуется
          заново и повторяет запрос);
      403 AccessDeniedError — нет прав на объект, роль, IP, api_key или тариф;
      404 NotFoundError — объект или маршрут не найден;
      409 DuplicateConflictError — повтор однотипного запроса;
      429/509 RateLimitError — превышен лимит запросов;
      5xx ServerError — ошибка сервера API.
    Проверка ответа моделью SDK: pydantic.ValidationError — ответ с HTTP 200 не совпал
      с моделью (поле отсутствует, null вместо значения, другой тип); список полей
      выводится при запуске, известные расхождения — в docs/spec-compatibility.md.
    Сеть: APIConnectionError (сервер недоступен, в т. ч. IP вне разрешённых стран),
      OperationTimeoutError (исчерпан общий лимит времени), RetryBudgetExceededError.
    Повтор при сетевой ошибке: только безопасные читающие; идемпотентность: да.
"""

