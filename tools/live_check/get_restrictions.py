"""get_restrictions — Список товарных ограничителей по договору, карте и группе карт

Что делает
    Получает товарные ограничители договора, карты или группы. Передаёт contract_id и
    опциональный card_id/group_id, выводит список ограничителей.
    Изменяет данные: нет. Тарификация: да. Демо-стенд: да.
    Вызов SDK: client.restrictions.get_restrictions(...)
    Раздел спецификации 1.1.60: Список товарных ограничителей по договору, карте и группе карт

HTTP-запрос
      GET /v1/restriction
    Параметры передаются: строка запроса.
    contract_id передаётся: header, query.
    Заголовки: api_key, date_time, session_id (после авторизации).

Параметры метода SDK
      contract_id: str | None, необязательный, по умолчанию None, тип в спецификации: string — ID контракта.
      card_id: str | None, необязательный, по умолчанию None, тип в спецификации: string — ID карты. Если ID карты и ID группы карт не переданы, то будут возвращены все товарные ограничители, привязанные к договору. Если передан ID карты, то будет возвращена информация о всех товарных ограничителях по карте, даже если передан ID группы карт
      group_id: str | None, необязательный, по умолчанию None, тип в спецификации: string — ID группы карт. Если передан ID группы карты, то будут возвращены все товарные ограничители указанной группы карт. Если передан ID карты и ID группы карт, то будет возвращена информация по карте

Модели проверки входящих данных (запрос)
      отдельной модели нет: параметры проверяются сигнатурой и проверками метода

Модели проверки исходящих данных (ответ API)
    RestrictionGetResponse:
      status: ResponseStatus, обязательное — Статус ответа API
      data: RestrictionList, обязательное — Типизированные данные ответа API
      timestamp: int | None, необязательное — Метка времени ответа API
    ResponseStatus:
      code: int, обязательное — Код выполнения API-операции
      message: str | None, необязательное — Текст статуса API-операции
      errors: list[dict[str, object]] | None, необязательное — Массив ошибок; отсутствует, если операция завершилась без ошибок
    RestrictionList:
      total_count: int, обязательное — Общее количество ограничителей
      result: list[RestrictionItem] | None, необязательное — Список ограничителей
    RestrictionItem:
      id: str, обязательное — ID ограничителя
      card_id: str | None, необязательное — ID карты, если ограничитель задан для карты
      group_id: str | None, необязательное — ID группы карт, если ограничитель задан для группы
      contract_id: str, обязательное — ID договора
      productType: str | None, необязательное — ID типа продукта (например, '1-CK231')
      productGroup: str | None, необязательное — ID группы продуктов (если применимо)
      productTypeName: str | None, необязательное — Название типа продукта
      productGroupName: str | None, необязательное — Название группы продуктов
      restriction_type: int | None, необязательное — Тип ограничения (1 – Разрешающий ограничитель, 2 – Запрещающий ограничитель)
      date: str, обязательное — Дата установки ограничителя (в формате MM/DD/YYYY HH:mm:ss)

Возможные ошибки
    До отправки запроса (локальные проверки SDK):
      специальных проверок нет
      pydantic.ValidationError / RequestValidationError — неверный тип или формат
      параметра по модели запроса.
    Ответ API (HTTP-код или status.code; текст сервера — в «Сообщение сервера: …»):
      400 ValidationError — неверные параметры или структура запроса;
      401 NotAuthenticatedError — сессия недействительна (SDK один раз авторизуется
          заново и повторяет запрос);
      403 AccessDeniedError — нет прав на объект, роль, IP, api_key или тариф;
      404 NotFoundError — объект или маршрут не найден;
      409 DuplicateConflictError — повтор однотипного запроса;
      429/509 RateLimitError — превышен лимит запросов;
      5xx ServerError — ошибка сервера API.
    Проверка ответа моделью SDK: pydantic.ValidationError — ответ с HTTP 200 не совпал
      с моделью (поле отсутствует, null вместо значения, другой тип); список полей
      выводится при запуске, известные расхождения — в docs/spec-compatibility.md.
    Сеть: APIConnectionError (сервер недоступен, в т. ч. IP вне разрешённых стран),
      OperationTimeoutError (исчерпан общий лимит времени), RetryBudgetExceededError.
    Повтор при сетевой ошибке: только безопасные читающие; идемпотентность: да.
"""

